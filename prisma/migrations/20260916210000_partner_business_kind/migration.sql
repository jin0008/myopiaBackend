-- 파트너 포털은 병원 모양 하나뿐이었다 - 가입 화면은 "병원명"을 묻고,
-- 로그인하면 병원 프로필 편집기(카카오 장소, 진료시간, 의사, 치료항목)로
-- 떨어진다. 안경점 사장에게는 채울 것이 하나도 없는 화면이다.
--
-- 표 이름은 그대로 둔다(hospital_account). 이름을 바꾸면 이 표를 참조하는
-- 모든 곳을 함께 옮겨야 하는데, 지금 필요한 것은 "이 계정이 어느 쪽인가"
-- 하나다. 이름과 뜻이 어긋나는 것은 이 주석으로 갚아 둔다.
--
-- 기존 계정은 모두 병원이다. 안경점 가입 길이 없었으니 다른 값일 수 없다.
ALTER TABLE "hospital_account"
    ADD COLUMN "business_kind" TEXT NOT NULL DEFAULT 'hospital';
